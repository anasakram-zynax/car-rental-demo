async function main() {
  console.log('\n=== Hotel Destinations Seed ===\n');

  const app = await NestFactory.createApplicationContext(AppModule, {
    logger: ['error', 'warn', 'log'],
  });

  try {
    const prisma = app.get(PrismaService);

    for (const dest of DESTINATIONS) {
      // Upsert the supported destination
      const existing = await prisma.destinations.findUnique({
        where: { code: dest.code },
      });

      let destination;
      if (existing) {
        destination = await prisma.destinations.update({
          where: { code: dest.code },
          data: {
            name: dest.name,
            normalizedName: dest.normalizedName,
            countryCode: dest.countryCode,
            countryName: dest.countryName,
            cityName: dest.cityName,
            displayOrder: dest.displayOrder,
            enabled: dest.enabled,
          },
        });
        console.log(`  Updated destination: ${dest.code} — ${dest.name}`);
      } else {
        destination = await prisma.destinations.create({
          data: {
            code: dest.code,
            name: dest.name,
            normalizedName: dest.normalizedName,
            countryCode: dest.countryCode,
            countryName: dest.countryName,
            cityName: dest.cityName,
            displayOrder: dest.displayOrder,
            enabled: dest.enabled,
            contentStatus: 'missing',
          },
        });
        console.log(`  Created destination: ${dest.code} — ${dest.name}`);
      }

      // Upsert Hotelbeds provider mapping
      await prisma.destinationSupplierCodes.upsert({
        where: {
          destinationId_provider: {
            destinationId: destination.id,
            provider: 'hotelbeds',
          },
        },
        create: {
          destinationId: destination.id,
          provider: 'hotelbeds',
          providerCode: dest.hotelbedsCode,
          providerCodeType: 'destination_code',
          enabled: true,
          syncStatus: 'missing',
        },
        update: {
          providerCode: dest.hotelbedsCode,
          enabled: true,
        },
      });
      console.log(`  Mapped Hotelbeds: ${dest.hotelbedsCode}`);

      // Upsert RateHawk provider mapping (disabled by default — region_id is a PLACEHOLDER)
      await prisma.destinationSupplierCodes.upsert({
        where: {
          destinationId_provider: {
            destinationId: destination.id,
            provider: 'ratehawk',
          },
        },
        create: {
          destinationId: destination.id,
          provider: 'ratehawk',
          providerCode: dest.ratehawkRegionId,
          providerCodeType: 'region_id',
          enabled: false, // disabled until region_id is verified via region dump
          syncStatus: 'missing',
        },
        update: {
          providerCode: dest.ratehawkRegionId,
          enabled: false,
        },
      });
      console.log(`  Mapped RateHawk: region_id=${dest.ratehawkRegionId} (DISABLED — verify via region dump, then enable in admin)`);
      console.log('');
    }

    console.log(`=== Seed Complete: ${DESTINATIONS.length} destinations with Hotelbeds + RateHawk mappings ===\n`);
    console.log('⚠  RateHawk region_ids are placeholders. To get real IDs:');
    console.log('   1. Call POST /api/b2b/v3/hotel/region/dump/ with your RateHawk credentials');
    console.log('   2. Search for each city in the decompressed JSONL output');
    console.log('   3. Update via admin panel: /admin/hotels/content/destinations/:id/providers\n');
  } finally {
    await app.close();
  }
}

main().catch((err) => {
  console.error('Seed failed:', err instanceof Error ? err.message : err);
  process.exit(1);
});
