export const SIDEBAR_WIDTH = "16rem";
export const SIDEBAR_WIDTH_MOBILE = "18rem";
export const SIDEBAR_WIDTH_ICON = "3rem";
export const SIDEBAR_KEYBOARD_SHORTCUT = "b";

type SidebarContextType = {
  state: "expanded" | "collapsed";
  open: boolean;
  setOpen: (open: boolean) => void;
  openMobile: boolean;
  setOpenMobile: (open: boolean) => void;
  isMobile: boolean;
  toggleSidebar: () => void;
};

const SidebarContext = createContext<SidebarContextType | null>(null);

export function useSidebar() {
  const context = useContext(SidebarContext);
  if (!context) {
    throw new Error("useSidebar must be used within a SidebarProvider.");
  }
  return context;
}

type SidebarProviderProps = ComponentProps<"div"> & {
  defaultOpen?: boolean;
  open?: boolean;
  onOpenChange?: (open: boolean) => void;
};

export function SidebarProvider({
  defaultOpen = true,
  open: openProp,
  onOpenChange: setOpenProp,
  className,
  style,
  children,
  ...props
}: SidebarProviderProps) {
  const isMobile = useIsMobile();
  const [openMobile, setOpenMobile] = useState(false);

  const [_open, _setOpen] = useState(defaultOpen);
  const open = openProp ?? _open;
  const setOpen = useCallback(
    (value: boolean | ((value: boolean) => boolean)) => {
      const openState = typeof value === "function" ? value(open) : value;
      if (setOpenProp) {
        setOpenProp(openState);
      } else {
        _setOpen(openState);
      }
    },
    [setOpenProp, open]
  );

  const toggleSidebar = useCallback(() => {
    return isMobile ? setOpenMobile((open) => !open) : setOpen((open) => !open);
  }, [isMobile, setOpen, setOpenMobile]);

  useEffect(() => {
    const handleKeyDown = (event: KeyboardEvent) => {
      if (
        event.key === SIDEBAR_KEYBOARD_SHORTCUT &&
        (event.metaKey || event.ctrlKey)
      ) {
        event.preventDefault();
        toggleSidebar();
      }
    };

    window.addEventListener("keydown", handleKeyDown);
    return () => window.removeEventListener("keydown", handleKeyDown);
  }, [toggleSidebar]);

  const state = open ? "expanded" : "collapsed";

  const contextValue = useMemo<SidebarContextType>(
    () => ({
      state,
      open,
      setOpen,
      isMobile,
      openMobile,
      setOpenMobile,
      toggleSidebar,
    }),
    [state, open, setOpen, isMobile, openMobile, setOpenMobile, toggleSidebar]
  );

  return (
    <SidebarContext.Provider value={contextValue}>
      <TooltipProvider delayDuration={0}>
        <div
          data-slot="sidebar-wrapper"
          style={
            {
              "--sidebar-width": SIDEBAR_WIDTH,
              "--sidebar-width-icon": SIDEBAR_WIDTH_ICON,
              ...style,
            } as CSSProperties
          }
          className={cn(
            "group/sidebar-wrapper flex min-h-svh w-full has-data-[variant=inset]:bg-sidebar",
            className
          )}
          {...props}
        >
          {children}
        </div>
      </TooltipProvider>
    </SidebarContext.Provider>
  );
}

type SidebarProps = ComponentProps<"div"> & {
  side?: "left" | "right";
  variant?: "sidebar" | "floating" | "inset";
  collapsible?: "offcanvas" | "icon" | "none";
};

export function Sidebar({
  side = "left",
  variant = "sidebar",
  collapsible = "offcanvas",
  className,
  children,
  ...props
}: SidebarProps) {
  const { isMobile, state, openMobile, setOpenMobile } = useSidebar();

  // ESC closes the mobile drawer (parity with the old Radix Sheet).
  useEffect(() => {
    if (!openMobile) return;
    const onKey = (event: KeyboardEvent) => {
      if (event.key === "Escape") setOpenMobile(false);
    };
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [openMobile, setOpenMobile]);

  // Deterministic body scroll lock while the drawer is open — NOT
  // react-remove-scroll. Radix's per-event touch/wheel interception cancelled
  // scrolling inside the drawer on tabs whose content made the nav overflow
  // (Dashboard, bookings tables): gestures were treated as "page scroll" and
  // swallowed. A plain CSS lock + the drawer's own scroller has no such logic.
  useEffect(() => {
    if (!openMobile) return;
    const previous = document.body.style.overflow;
    document.body.style.overflow = "hidden";
    return () => {
      document.body.style.overflow = previous;
    };
  }, [openMobile]);

  if (isMobile) {
    // Mobile drawer WITHOUT Radix Dialog and WITHOUT class-flip transitions.
    // Both historical bugs lived in "flip a class and let CSS transition":
    //  - Radix's dialog scroll-lock swallowed touch gestures per-tab (fixed
    //    by dropping the Dialog), and
    //  - on heavy tabs (Dashboard charts, bookings tables) the main thread
    //    saturates and a transition started by a class flip can stick at its
    //    FROM value — reproduced live: drawer stuck off-screen while "open",
    //    overlay stuck invisible but still intercepting every tap.
    // So the drawer + overlay now MOUNT only while open, already in their
    // open position; the entry animation is a keyframe whose end state IS the
    // static style, so a janky frame can never freeze them mid-transition.
    if (!openMobile) return null;

    return (
      <>
        <div
          aria-hidden="true"
          onClick={() => setOpenMobile(false)}
          className="sidebar-overlay-in fixed inset-0 z-[55] bg-black/20 lg:hidden"
        />
        <div
          data-slot="sidebar"
          data-sidebar="sidebar"
          data-mobile="true"
          className={cn(
            // overflow-hidden + flex: the DRAWER frame never scrolls. The
            // inner nav ([data-slot="sidebar-scroll"]) is the single scroll
            // container. lg:hidden (not md:hidden): useIsMobile flips at
            // 1024px, so with md:hidden the drawer was display:none at
            // 768–1023px — tapping the trigger "opened" an invisible drawer
            // while the desktop sidebar branch never rendered (same hook).
            "fixed inset-y-0 z-[60] flex w-(--sidebar-width) flex-col overflow-hidden bg-sidebar text-sidebar-foreground shadow-lg lg:hidden",
            side === "left"
              ? "left-0 sidebar-drawer-in-left"
              : "right-0 sidebar-drawer-in-right",
            className
          )}
          style={
            {
              "--sidebar-width": SIDEBAR_WIDTH_MOBILE,
            } as CSSProperties
          }
          {...props}
        >
          <div className="flex h-full w-full flex-col overflow-hidden">{children}</div>
        </div>
      </>
    );
  }

  if (collapsible === "none") {
    return (
      <div
        data-slot="sidebar"
        className={cn(
          "flex h-full w-(--sidebar-width) flex-col bg-sidebar text-sidebar-foreground",
          className
        )}
        {...props}
      >
        {children}
      </div>
    );
  }

  return (
    <div
      data-slot="sidebar"
      data-state={state}
      data-collapsible={state === "collapsed" ? collapsible : ""}
      data-variant={variant}
      data-side={side}
      className="group peer hidden lg:block text-sidebar-foreground"
    >
      {/* This is what handles the sidebar gap on desktop */}
      <div
        className={cn(
          "duration-200 relative h-svh w-(--sidebar-width) bg-transparent transition-[width] ease-linear",
          "group-data-[collapsible=offcanvas]:w-0",
          "group-data-[side=right]:rotate-180",
          variant === "floating" || variant === "inset"
            ? "group-data-[collapsible=icon]:w-[calc(var(--sidebar-width-icon)+(--spacing(4)))]"
            : "group-data-[collapsible=icon]:w-(--sidebar-width-icon)"
        )}
      />
      <div
        className={cn(
          "duration-200 fixed inset-y-0 z-10 hidden h-svh w-(--sidebar-width) transition-[left,right,width] ease-linear lg:flex",
          side === "left"
            ? "left-0 group-data-[collapsible=offcanvas]:left-[calc(var(--sidebar-width)*-1)]"
            : "right-0 group-data-[collapsible=offcanvas]:right-[calc(var(--sidebar-width)*-1)]",
          variant === "floating" || variant === "inset"
            ? "p-2 group-data-[collapsible=icon]:w-[calc(var(--sidebar-width-icon)+(--spacing(4))+2px)]"
            : "group-data-[collapsible=icon]:w-(--sidebar-width-icon) group-data-[side=left]:border-r group-data-[side=right]:border-l",
          className
        )}
        {...props}
      >
        <div
          data-sidebar="sidebar"
          className="flex h-full w-full flex-col bg-sidebar group-data-[variant=floating]:rounded-lg group-data-[variant=floating]:border group-data-[variant=floating]:border-sidebar-border group-data-[variant=floating]:shadow-sm"
        >
          {children}
        </div>
      </div>
    </div>
  );
}

export function SidebarTrigger({
  className,
  onClick,
  ...props
}: ComponentProps<"button">) {
  const { toggleSidebar } = useSidebar();

  return (
    // Raw button with semantic tokens (Reference-2 shadcn ghost style) so it
    // follows the scoped admin theme instead of the frontside teal Button.
    <button
      data-slot="sidebar-trigger"
      data-sidebar="trigger"
      type="button"
      className={cn(
        "inline-flex h-9 w-9 items-center justify-center rounded-lg text-muted-foreground transition-colors hover:bg-accent hover:text-accent-foreground",
        className
      )}
      onClick={(event) => {
        onClick?.(event);
        toggleSidebar();
      }}
      {...props}
    >
      {/* Reference-2 trigger icon: lucide PanelLeft */}
      <svg
        width="16"
        height="16"
        viewBox="0 0 16 16"
        fill="none"
        xmlns="http://www.w3.org/2000/svg"
        className="h-4 w-4"
        aria-hidden="true"
      >
        <path
          d="M6 2H2.5C2.22386 2 2 2.22386 2 2.5V13.5C2 13.7761 2.22386 14 2.5 14H6V2Z"
          fill="currentColor"
        />
        <path
          d="M7 2H13.5C13.7761 2 14 2.22386 14 2.5V13.5C14 13.7761 13.7761 14 13.5 14H7V2Z"
          fill="currentColor"
          fillOpacity="0.35"
        />
      </svg>
      <span className="sr-only">Toggle Sidebar</span>
    </button>
  );
}

